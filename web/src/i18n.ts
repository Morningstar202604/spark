export type TranslationKey = keyof (typeof dict)["zh"]

export function t(key: TranslationKey, lang: Lang, vars?: Record<string, string | number>): string {
  let str: string = dict[lang][key] ?? key
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      str = str.replace(`{${k}}`, String(v))
    }
  }
  return str
}

export function getDefaultLang(): Lang {
  const saved = localStorage.getItem("spark-lang")
  return saved === "en" ? "en" : "zh"
}

export function setDefaultLang(lang: Lang) {
  localStorage.setItem("spark-lang", lang)
}
