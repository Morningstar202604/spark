def test_check_cached_refreshes_on_stale_cache(tmp_path: Path, monkeypatch) -> None:
    import json as _json

    home = tmp_path / "home"
    home.mkdir()
    (home / "update-check.json").write_text(
        _json.dumps({"checked_at": 0, "latest": "0.0.1"}), encoding="utf-8"
    )
    release = updater.ReleaseInfo(version="9.9.9", tag="v9.9.9", notes="", assets=[])
    monkeypatch.setattr(updater, "fetch_latest", lambda *a, **k: release)
    assert updater.check_cached(home) == "9.9.9"
    saved = _json.loads((home / "update-check.json").read_text(encoding="utf-8"))
    assert saved["latest"] == "9.9.9"


