def test_install_archive_preserves_old_on_copy_failure(tmp_path: Path, monkeypatch) -> None:
    exe = tmp_path / "spark.exe"
    exe.write_bytes(b"OLD")
    archive = tmp_path / "pkg.zip"
    with zipfile.ZipFile(archive, "w") as zf:
        zf.writestr("spark/spark.exe", b"NEW")

    def boom(*a, **k):
        raise OSError("disk full")

    monkeypatch.setattr(updater.shutil, "copy2", boom)
    with pytest.raises(updater.UpdateError, match="替换可执行文件失败"):
        updater.install_archive(archive, exe)
    assert exe.read_bytes() == b"OLD", "旧可执行文件必须被回滚"


def test_safe_extract_rejects_zip_path_traversal(tmp_path: Path) -> None:
    archive = tmp_path / "evil.zip"
    with zipfile.ZipFile(archive, "w") as zf:
        zf.writestr("../../evil.txt", b"pwned")
    dest = tmp_path / "out"
    dest.mkdir()
    with pytest.raises(updater.UpdateError, match="路径逃逸"):
        updater._safe_extract(archive, dest)
    assert not (tmp_path.parent / "evil.txt").exists()


def test_safe_extract_rejects_tar_path_traversal(tmp_path: Path) -> None:
    import io
    import tarfile

    archive = tmp_path / "evil.tar.gz"
    with tarfile.open(archive, "w:gz") as tf:
        info = tarfile.TarInfo("../evil.txt")
        payload = b"pwned"
        info.size = len(payload)
        tf.addfile(info, io.BytesIO(payload))
    dest = tmp_path / "out"
    dest.mkdir()
    with pytest.raises(updater.UpdateError, match="路径逃逸"):
        updater._safe_extract(archive, dest)


def test_safe_extract_rejects_symlink_members(tmp_path: Path) -> None:
    import tarfile

    archive = tmp_path / "link.tar.gz"
    with tarfile.open(archive, "w:gz") as tf:
        info = tarfile.TarInfo("link")
        info.type = tarfile.SYMTYPE
        info.linkname = "/etc/passwd"
        tf.addfile(info)
    dest = tmp_path / "out"
    dest.mkdir()
    with pytest.raises(updater.UpdateError, match="链接/设备"):
        updater._safe_extract(archive, dest)
